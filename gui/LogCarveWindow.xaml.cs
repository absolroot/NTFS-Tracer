            sourceLock?.Dispose();
            if (current == null)
                DeleteIndex(dbPath);
        };
        Busy(false);
    }

    private static SqliteConnection OpenDb(string path)
    {
        var db = new SqliteConnection(new SqliteConnectionStringBuilder
        {
            DataSource = path,
            Mode = SqliteOpenMode.ReadOnly,
            Pooling = false
        }.ToString());
        try
        {
            db.Open();
            db.CreateFunction<string, string>("caption", Caption, true);
            return db;
        }
        catch { db.Dispose(); throw; }
    }

    private static void DeleteIndex(string? path)
    {
        if (path == null)
            return;
        foreach (var file in new[] { path, path + "-journal", path + "-wal", path + "-shm" })
            try
            {
                File.Delete(file);
            }
            catch (IOException) { }
            catch (UnauthorizedAccessException) { }
    }

    private void Busy(bool busy)
    {
        bool hasIndex = dbPath != null;
        ScanOpenSource.IsEnabled = Pick.IsEnabled = !busy;
        Hint.Visibility = !busy && !hasIndex ? Visibility.Visible : Visibility.Collapsed;
        Rows.Visibility = Mode.Visibility = ResultsNavigation.Visibility = ResultsExport.Visibility = hasIndex ? Visibility.Visible : Visibility.Collapsed;
        PageLimit.IsEnabled = !busy && hasIndex;
        Mode.IsEnabled = !busy && hasIndex;
        Stop.Visibility = busy ? Visibility.Visible : Visibility.Collapsed;
        Save.IsEnabled = !busy && hasIndex && Count > 0;
        Prev.IsEnabled = !busy && start > 0;
        Next.IsEnabled = !busy && start + pageSize < Count;
    }

    private long Count => Mode.SelectedIndex == 0 ? pageCount : headerCount;
    private string Projection => Mode.SelectedIndex == 0 ? PageQuery : HeaderQuery;
    private string Order
    {
        get
        {
            // SortMemberPath comes from the fixed projection, independently of the localized header.
            string key = "[" + sortField + "]";
            if (sortField is "Validation" or "Header and data location")
                key = $"caption({key})";
            return key + (descending ? " DESC" : " ASC") + ", [Dump offset]" + (Mode.SelectedIndex == 0 ? "" : ", [Page start]");
        }
    }
    private string SelectQuery => $"SELECT * FROM ({Projection}) ORDER BY {Order}";

