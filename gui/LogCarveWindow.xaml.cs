    private async Task ExportCsv(string destination)
    {
        if (dbPath == null || sourcePath == null || sourceHash == null)
            return;
        if (File.Exists(destination))
        {
            State.Text = L.T("같은 이름의 파일이 있습니다. 새 CSV 파일 이름을 선택하세요.", "This file already exists. Choose a new CSV file name.");
            return;
        }
        using var work = CancellationTokenSource.CreateLinkedTokenSource(lifetime);
        current = work;
        Busy(true);
        var (path, query, hash, original) = (dbPath, SelectQuery, sourceHash, sourcePath);
        string method = Mode.SelectedIndex == 0 ? "carved_RCRD_page_candidate" : "carved_RCRD_record_header_candidate";
        var temp = Path.Combine(Path.GetDirectoryName(destination)!, Guid.NewGuid().ToString("N") + ".partial");
        try
        {
            State.Text = L.T("현재 목록 전체를 CSV로 저장하고 있습니다.", "Saving the entire list to CSV.");
            await Task.Run(() =>
            {
                using var db = OpenDb(path);
                using var cmd = db.CreateCommand();
                cmd.CommandText = query;
                using var reader = cmd.ExecuteReader();
                using var stream = new FileStream(temp, FileMode.CreateNew, FileAccess.Write, FileShare.None);
                using var writer = new StreamWriter(stream, new UTF8Encoding(true));
                string Quote(string value) => "\"" + value.Replace("\"", "\"\"") + "\"";
                writer.WriteLine("source_SHA256," + string.Join(",", Enumerable.Range(0, reader.FieldCount).Select(i => CsvColumn(reader.GetName(i)))) + ",source_path,analysis_method");
                while (reader.Read())
                {
                    work.Token.ThrowIfCancellationRequested();
                    var fields = Enumerable.Range(0, reader.FieldCount).Select(i => Quote(Convert.ToString(reader.GetValue(i), CultureInfo.InvariantCulture) ?? ""));
                    writer.WriteLine(hash + "," + string.Join(",", fields) + "," + Quote(original) + "," + method);
                }
            }, work.Token);
            work.Token.ThrowIfCancellationRequested();
            File.Move(temp, destination);
            if (!lifetime.IsCancellationRequested)
                SavedOutput.Show(State, destination, L.T("후보 {0:N0}건 저장", "{0:N0} candidates saved", Count));
        }
        catch (OperationCanceledException) { State.Text = L.T("CSV 저장을 취소했습니다.", "CSV save cancelled."); }
        catch (Exception ex) { State.Text = L.T("CSV를 저장할 수 없습니다. ", "Could not save the CSV. ") + ex.Message; }
        finally
        {
            try
            {
                File.Delete(temp);
            }
            catch (IOException) { }
            catch (UnauthorizedAccessException) { }
            current = null;
            if (lifetime.IsCancellationRequested)
                DeleteIndex(dbPath);
            else
                Busy(false);
        }
    }
