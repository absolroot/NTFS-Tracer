    private async void PageSizeChanged(object sender, SelectionChangedEventArgs e)
    {
        if (sender is not ComboBox { SelectedValue: int size } || size == pageSize)
            return;
        long ordinal = start + Math.Max(0, Rows.SelectedIndex);
        PageSizeOption.Remember(size);
        pageSize = size;
        await LoadPage(first: ordinal / size * size, retainedIndex: (int)(ordinal % size));
    }

    private async void PreviousPage(object sender, RoutedEventArgs e)
    {
        await LoadPage(first: Math.Max(0, start - pageSize));
    }
    private async void NextPage(object sender, RoutedEventArgs e)
    {
        await LoadPage(first: start + pageSize);
    }

    private async void SortRows(object sender, DataGridSortingEventArgs e)
    {
        e.Handled = true;
        if (current != null || dbPath == null)
            return;
        var prior = (sortField, descending, explicitSort);
        var direction = SortCycle.Next(explicitSort && sortField == e.Column.SortMemberPath, descending);
        explicitSort = direction.HasValue;
        descending = direction ?? false;
        sortField = explicitSort ? e.Column.SortMemberPath : "Dump offset";
        var chosen = Rows.SelectedItem as DataRowView;
        long? offset = chosen == null ? null : Convert.ToInt64(chosen["Dump offset"], CultureInfo.InvariantCulture);
        long? pageOffset = chosen != null && Mode.SelectedIndex == 1 ? Convert.ToInt64(chosen["Page start"], CultureInfo.InvariantCulture) : null;
        if (!await LoadPage(offset, pageOffset))
        {
            (sortField, descending, explicitSort) = prior;
            UpdateSortArrows();
        }
    }

    private async Task<bool> LoadPage(long? anchor = null, long? pageOffset = null, long first = 0, int? retainedIndex = null)
    {
        if (dbPath is not { } path)
            return false;
        string ordered = SelectQuery, projection = Projection, order = Order;
        using var ownWork = current == null ? CancellationTokenSource.CreateLinkedTokenSource(lifetime) : null;
        if (ownWork != null)
        {
            current = ownWork;
            Busy(true);
        }
        var token = current!.Token;
        try
        {
            var (table, offset, selected) = await Task.Run(() =>
            {
                using var db = OpenDb(path);
                SQLitePCL.raw.sqlite3_progress_handler(db.Handle, 4096, static state => ((CancellationToken)state).IsCancellationRequested ? 1 : 0, token);
                using var cmd = db.CreateCommand();
                long selection = 0;
                if (anchor.HasValue)
                {
                    cmd.CommandText = $"SELECT ord FROM (SELECT *,row_number() OVER (ORDER BY {order})-1 AS ord FROM ({projection})) WHERE [Dump offset]=$pos" +
                        (pageOffset.HasValue ? " AND [Page start]=$page" : "");
                    cmd.Parameters.AddWithValue("$pos", anchor.Value);
                    if (pageOffset.HasValue)
                        cmd.Parameters.AddWithValue("$page", pageOffset.Value);
                    selection = Convert.ToInt64(cmd.ExecuteScalar(), CultureInfo.InvariantCulture);
                    first = selection / pageSize * pageSize;
                }
                cmd.CommandText = ordered + " LIMIT $size OFFSET $start";
                cmd.Parameters.Clear();
                cmd.Parameters.AddWithValue("$size", pageSize);
                cmd.Parameters.AddWithValue("$start", first);
                using var reader = cmd.ExecuteReader();
                var result = new DataTable();
                for (int i = 0; i < reader.FieldCount; i++)
                    result.Columns.Add(reader.GetName(i), typeof(object));
                while (reader.Read())
                {
                    token.ThrowIfCancellationRequested();
                    var values = new object[reader.FieldCount];
                    reader.GetValues(values);
                    for (int i = 0; i < values.Length; i++)
                        if (values[i] is string value && reader.GetName(i) is ("Validation" or "Header and data location"))
                            values[i] = Caption(value);
                    result.Rows.Add(values);
                }
                return (result, first, (int)(selection % pageSize));
            }, token);
            token.ThrowIfCancellationRequested();
            start = offset;
            Raw.ClearView();
            Rows.ItemsSource = table.DefaultView;
            UpdateSortArrows();
            if (table.Rows.Count > 0)
            {
                Rows.SelectedIndex = retainedIndex ?? selected;
                if (anchor.HasValue || retainedIndex.HasValue)
                    Rows.ScrollIntoView(Rows.SelectedItem);
            }
            CsvAction.Header = Mode.SelectedIndex == 0
                ? L.T("페이지 후보 {0:N0}개를 CSV로 내보내기…", "Export all {0:N0} page candidates as CSV…", Count)
                : L.T("헤더 후보 {0:N0}개를 CSV로 내보내기…", "Export all {0:N0} header candidates as CSV…", Count);
            State.Text = Count == 0 ? L.T("이 목록에 해당하는 후보가 없습니다.", "No candidates for this list.")
                : L.T("후보 {0:N0}개 중 {1:N0}–{2:N0}", "Candidates {1:N0}–{2:N0} of {0:N0}", Count, start + 1, start + table.Rows.Count);
            Busy(current != null);
            return true;
        }
        catch (Exception) when (token.IsCancellationRequested) { if (!lifetime.IsCancellationRequested) State.Text = L.T("조회가 취소되었습니다.", "Reading cancelled."); }
        catch (Exception ex) { Raw.ClearView(); Rows.ItemsSource = null; State.Text = ex.Message; }
        finally
        {
            if (ownWork != null)
            {
                current = null;
                if (lifetime.IsCancellationRequested)
                    DeleteIndex(dbPath);
                else
                    Busy(false);
            }
        }
        return false;
    }
    private void UpdateSortArrows()
    {
        foreach (var column in Rows.Columns)
            column.SortDirection = explicitSort && column.SortMemberPath == sortField
                ? descending ? System.ComponentModel.ListSortDirection.Descending : System.ComponentModel.ListSortDirection.Ascending : null;
    }
    private void MakeColumn(object sender, DataGridAutoGeneratingColumnEventArgs e)
    {
        if (e.PropertyName == "Header HEX")
        {
            e.Cancel = true;
            return;
        }
        string key = e.PropertyName;
        e.Column.Header = Caption(key);
        e.Column.SortMemberPath = key;
        // DataTable uses object columns to preserve SQLite NULL and numeric values.
        // The sorter runs against SQLite, independently of WPF's object-type default.
        e.Column.CanUserSort = true;
        if (e.Column is DataGridTextColumn col)
        {
            col.Binding = new Binding("[" + key + "]") { Converter = new CarveValue(key) };
            col.ElementStyle = (Style)FindResource("Desk.LogText");
        }
    }
    private sealed class CarveValue(string key) : IValueConverter
    {
        public object Convert(object value, Type target, object parameter, CultureInfo culture)
        {
            if (value is null or DBNull)
                return "—";
            if (key == "Free space start" && value is long n && n == 0)
                return L.T("미기록", "Not specified");
            if (key is "Dump offset" or "Page start" or "Page offset" or "Free space start" && value is long pos)
                return $"0x{pos:X}";
            if (key is "LSN" or "Last end LSN" or "Previous LSN" or "Next undo LSN" && value is string lsn)
                return lsn == "0000000000000000" && key is "Previous LSN" or "Next undo LSN" ? L.T("연결 없음", "No link") : "0x" + lsn;
            if (key == "Type code" && value is long kind)
                return kind switch
                {
                    1 => "ClientRecord (1)",
                    2 => "ClientRestart (2)",
                    _ => kind.ToString(culture)
                };
            return value;
        }
        public object ConvertBack(object value, Type target, object parameter, CultureInfo culture) => throw new NotSupportedException();
    }
    private void RowChanged(object sender, SelectionChangedEventArgs e)
    {
        if (Rows.SelectedItem is not DataRowView row)
        {
            Raw.ClearView();
            EvidencePanel.Visibility = Visibility.Collapsed;
            return;
        }
        long pos = Convert.ToInt64(row["Dump offset"], CultureInfo.InvariantCulture);
        byte[] bytes = Convert.FromHexString((string)row["Header HEX"]);
        var fields = row.DataView.Table!.Columns.Contains("Page offset")
            ? LogHeaderFields.Record(bytes, Convert.ToInt64(row["Page offset"], CultureInfo.InvariantCulture))
            : LogHeaderFields.Page(bytes);
        EvidencePanel.Visibility = Visibility.Visible;
        RawLabel.Text = L.T("파일 오프셋 0x{0:X}   ·   보정 전 헤더 {1:N0} B", "File offset 0x{0:X}   ·   {1:N0} header bytes before fixups", pos, bytes.Length);
        Raw.ShowBytes(bytes, pos, fields);
    }

