    private const string PageQuery = """
        SELECT pos AS [Dump offset], size AS [Page size],
          CASE status WHEN 'usa_ok' THEN 'USA match' WHEN 'truncated' THEN 'Truncated'
             WHEN 'usa_mismatch' THEN 'Sector trailer mismatch' WHEN 'invalid_usa' THEN 'Invalid USA number' ELSE status END AS [Validation],
          bad_stride + 1 AS [First mismatched sector (1-based)],next_offset AS [Free space start],
          last_end_lsn AS [Last end LSN],hex(raw_header) AS [Header HEX]
          FROM carved_pages
        """;
    private const string HeaderQuery = """
        SELECT pos AS [Dump offset],page_pos AS [Page start],page_offset AS [Page offset],
