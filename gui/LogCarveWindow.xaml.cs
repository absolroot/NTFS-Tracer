    private async Task InspectSource(string path)
    {
        using var work = CancellationTokenSource.CreateLinkedTokenSource(lifetime);
        current = work;
        Busy(true);
        string temp = Path.Combine(Path.GetTempPath(), "NtfsTracer-logcarve-" + Guid.NewGuid().ToString("N") + ".sqlite");
        FileStream? locked = null;
        try
        {
            locked = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read);
            State.Text = L.T("파일을 검사하고 있습니다.", "Scanning the file.");
            await EngineProcess.RunAsync("logcarve", path, temp, work.Token, line =>
            {
                var parts = line.Split(' ');
                if (parts.Length == 3 && parts[0] == "read" && long.TryParse(parts[1], out var read) && long.TryParse(parts[2], out var total))
                    State.Text = L.T("파일을 검사하고 있습니다. {0:N0} / {1:N0}바이트", "Scanning the file. {0:N0} / {1:N0} bytes", read, total);
            });
            using (var db = OpenDb(temp))
            using (var cmd = db.CreateCommand())
            {
                EngineIndexFormat.Validate(db, EngineArtifact.CarvedLog);
                cmd.CommandText = """
                    SELECT hash,bytes,rejected,(SELECT count(*) FROM carved_pages),
                    (SELECT count(*) FROM carved_headers),(SELECT count(*) FROM carved_pages WHERE status='usa_ok')
                    FROM carve_summary
                    """;
                using var reader = cmd.ExecuteReader();
                if (!reader.Read())
                    throw new InvalidDataException(L.T("카빙 결과에 요약 정보가 없습니다.", "No summary in the carving results."));
                sourceHash = reader.GetString(0);
                pageCount = reader.GetInt64(3);
                headerCount = reader.GetInt64(4);
                sourcePath = path;
                SourceLabel.Text = Path.GetFileName(path);
                SourceLabel.ToolTip = path;
                SourceBox.Visibility = Visibility.Visible;
                SourceBox.IsExpanded = false;
                SourceDetails.Text = L.T("{0}\nSHA-256  {1}\n{2:N0}바이트 · 페이지 후보 {3:N0}개 (USA 일치 {4:N0}개) · 레코드 헤더 후보 {5:N0}개 · 헤더 조건에서 제외한 서명 {6:N0}개", "{0}\nSHA-256  {1}\n{2:N0} bytes · {3:N0} page candidates ({4:N0} USA matches) · {5:N0} record header candidates · {6:N0} signatures excluded by header checks", sourcePath, sourceHash, reader.GetInt64(1), pageCount, reader.GetInt64(5), headerCount, reader.GetInt64(2));
            }
            DeleteIndex(dbPath);
            dbPath = temp;
            sourceLock?.Dispose();
            sourceLock = locked;
            locked = null;
            Rows.ItemsSource = null;
            start = 0;
            sortField = "Dump offset";
            descending = explicitSort = false;
            await LoadPage();
        }
        catch (OperationCanceledException) { State.Text = L.T("검사를 취소했습니다.", "Scan cancelled."); }
        catch (Exception ex) { State.Text = L.T("파일을 검사할 수 없습니다. ", "Could not scan the file. ") + ex.Message; }
        finally
        {
            locked?.Dispose();
            if (dbPath != temp)
                DeleteIndex(temp);
            current = null;
            if (lifetime.IsCancellationRequested)
                DeleteIndex(dbPath);
            else
                Busy(false);
        }
    }

    private void StopWork(object sender, RoutedEventArgs e) => current?.Cancel();
    private async void ModeChanged(object sender, SelectionChangedEventArgs e)
    {
        if (dbPath == null || current != null)
            return;
        Rows.ItemsSource = null;
        start = 0;
        sortField = "Dump offset";
