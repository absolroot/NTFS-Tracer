          client_bytes AS [Client data size],kind AS [Type code],txid AS [Transaction ID],
          CASE region WHEN 'slack' THEN 'Inside slack' WHEN 'overlap' THEN 'Overlaps slack boundary'
          WHEN 'before_free' THEN 'Before slack' ELSE 'Unknown slack location' END AS [Header and data location],
          hex(raw_header) AS [Header HEX] FROM carved_headers
        """;

